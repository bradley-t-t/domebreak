// Rasterizes the political country polygons from public/assets/regions-seed.geojson
// (keyed by their gid0 / ISO3 code) into a 0.25-degree world ownership grid and
// emits src/game/geo/countryGrid.js. Each cell holds a 1-byte index into a GIDS
// table (0 = no country / ocean). The grid is the sim's ground truth for "which
// nation politically owns this point" — the same border the human player is
// bound to — so the AI can be gated on its own country instead of a Voronoi disk.
//
//   node scripts/gen-country-grid.mjs
import {readFileSync, writeFileSync} from "node:fs";
import {dirname, join} from "node:path";
import {fileURLToPath} from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const W = 1440, H = 720, STEP = 360 / W; // 0.25 degrees per cell — matches seaGrid

const geo = JSON.parse(readFileSync(join(root, "public/assets/regions-seed.geojson"), "utf8"));

// Group every region's rings under its country code. A Polygon is [ring, ...];
// a MultiPolygon is [[ring, ...], ...]. Even-odd fill per country handles both
// outer boundaries and holes, exactly as gen-sea-grid does for islands.
const ringsByGid = new Map();
for (const f of geo.features) {
    const gid = f.properties.gid0;
    if (!gid) continue;
    let arr = ringsByGid.get(gid);
    if (!arr) ringsByGid.set(gid, arr = []);
    const polys = f.geometry.type === "MultiPolygon" ? f.geometry.coordinates : [f.geometry.coordinates];
    for (const poly of polys) for (const ring of poly) arr.push(ring);
}

// Deterministic GIDS table: index 0 reserved for "no country", 1..N sorted.
const gids = [...ringsByGid.keys()].sort();
if (gids.length > 255) throw new Error(`${gids.length} countries — exceeds 1-byte index`);
const gidIndex = new Map(gids.map((g, i) => [g, i + 1]));
console.log(`countries: ${gids.length}, regions: ${geo.features.length}`);

// Even-odd scanline fill, one country at a time, writing its index into every
// covered cell. Later countries overwrite earlier ones on shared border cells —
// border precision is one ~27 km cell, far tighter than the 550 km Voronoi disk
// it replaces.
const owner = new Uint8Array(W * H);
for (const gid of gids) {
    const idx = gidIndex.get(gid);
    const rings = ringsByGid.get(gid);
    const rowHits = new Map(); // row -> crossing x's
    for (const ring of rings) {
        for (let i = 0; i < ring.length; i++) {
            const [x1, y1] = ring[i], [x2, y2] = ring[(i + 1) % ring.length];
            if (y1 === y2) continue;
            const lo = Math.min(y1, y2), hi = Math.max(y1, y2);
            const r0 = Math.max(0, Math.ceil((lo + 90) / STEP - 0.5));
            const r1 = Math.min(H - 1, Math.floor((hi + 90) / STEP - 0.5));
            for (let r = r0; r <= r1; r++) {
                const lat = -90 + (r + 0.5) * STEP;
                if ((y1 <= lat) === (y2 <= lat)) continue;
                let hits = rowHits.get(r);
                if (!hits) rowHits.set(r, hits = []);
                hits.push(x1 + ((lat - y1) * (x2 - x1)) / (y2 - y1));
            }
        }
    }
    for (const [r, xs] of rowHits) {
        xs.sort((a, b) => a - b);
        for (let i = 0; i + 1 < xs.length; i += 2) {
            const c0 = Math.max(0, Math.ceil((xs[i] + 180) / STEP - 0.5));
            const c1 = Math.min(W - 1, Math.floor((xs[i + 1] + 180) / STEP - 0.5));
            for (let c = c0; c <= c1; c++) owner[r * W + c] = idx;
        }
    }
}
const covered = owner.reduce((a, b) => a + (b ? 1 : 0), 0);
console.log(`land fraction after rasterize: ${(covered / (W * H) * 100).toFixed(1)}%`);

// Run-length encode: country ownership is long constant runs along each row, so
// RLE shrinks the ~1 MB raw grid by ~10x. Each run is 3 bytes: value, count-lo,
// count-hi (16-bit count, runs over 65535 split). Decoded once at module load.
const runs = [];
for (let i = 0; i < W * H;) {
    const v = owner[i];
    let n = 1;
    while (i + n < W * H && owner[i + n] === v && n < 65535) n++;
    runs.push(v, n & 0xff, n >> 8);
    i += n;
}
const bytes = Uint8Array.from(runs);
const b64 = Buffer.from(bytes).toString("base64");

writeFileSync(join(root, "src/game/geo/countryGrid.js"),
    `// Generated by scripts/gen-country-grid.mjs — do not edit by hand.
// 0.25-degree world political-ownership grid rasterized from regions-seed.geojson
// by gid0. Cell (row i/W from lat -90, col i%W from lng -180) holds a 1-byte
// index into GIDS; 0 = no country (ocean / unclaimed). RLE payload: 3 bytes per
// run (value, count-lo, count-hi). Decoded and queried in ./countryOwner.js.
export const COUNTRY_W = ${W};
export const COUNTRY_H = ${H};
export const GIDS = ${JSON.stringify(["", ...gids])};
export const COUNTRY_RLE_B64 = "${b64}";
`);
console.log(`wrote src/game/geo/countryGrid.js (${(b64.length / 1024).toFixed(0)}KB base64, ${runs.length / 3} runs)`);
